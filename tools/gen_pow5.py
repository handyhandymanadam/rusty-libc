#!/usr/bin/env python3
"""Generates crates/rusty-libc-core/src/pow5.rs: 128-bit approximations of 5^q for q in -342..=308, the table
the Eisel-Lemire decimal-to-binary algorithm multiplies a 64-bit decimal significand with (Lemire,
"Number Parsing at a Gigabyte per Second", 2021).

Each entry is (hi, lo) of a 128-bit integer whose top bit is set:
  q >= 0: the top 128 bits of 5^q, truncated (exact while 5^q < 2^128, i.e. q <= 55);
  q <  0: floor(2^b / 5^-q) + 1 with b = z + 127 for q >= -27 and b = 2z + 128 otherwise, z = ceil(log2(5^-q)),
          halved until it fits 128 bits (rounded up: the error bounds of the algorithm assume this).
Pure integer arithmetic; nothing is copied from any library."""
import os

LO, HI = -342, 308


def entry(q):
    if q >= 0:
        p = 5 ** q
        bl = p.bit_length()
        v = p >> (bl - 128) if bl > 128 else p << (128 - bl)
    else:
        n = 5 ** (-q)
        z = (n - 1).bit_length()  # smallest z with 2^z >= n
        if q >= -27:
            v = (1 << (z + 127)) // n + 1
        else:
            v = (1 << (2 * z + 128)) // n + 1
            while v >= 1 << 128:
                v >>= 1
    assert v.bit_length() == 128
    return v >> 64, v & ((1 << 64) - 1)


def main():
    rows = [entry(q) for q in range(LO, HI + 1)]
    out = ["//! 128-bit powers of five for the Eisel-Lemire conversion (generated by tools/gen_pow5.py; do not edit).",
           "//! Entry `i` is 5^(i + SMALLEST_POW5) as (high word, low word), normalised so the top bit is set.",
           "",
           f"pub const SMALLEST_POW5: i64 = {LO};",
           f"pub const LARGEST_POW5: i64 = {HI};",
           "",
           f"pub static POW5_128: [(u64, u64); {len(rows)}] = ["]
    for i in range(0, len(rows), 3):
        out.append("    " + " ".join(f"(0x{h:016x}, 0x{l:016x})," for h, l in rows[i:i + 3]))
    out.append("];")
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "rusty-libc-core", "src", "pow5.rs")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(path), len(rows), "entries")


main()
