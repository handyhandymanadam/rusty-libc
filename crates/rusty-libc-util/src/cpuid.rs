/// Leaf 7 ebx bit 0 (FSGSBASE), leaf 7 ecx bits 3 (PKU, active when OSPKE is) and 23 (KL), leaf 7 edx bit 11
/// RTM_ALWAYS_ABORT (leaf index 1) and RTM (ebx bit 11), leaf 7/1 edx bit 21 (APX_F), leaf 19.
const FSGSBASE: u32 = 1 << 0;
const PKU: u32 = 1 << 3;
const OSPKE: u32 = 1 << 4;
const KL: u32 = 1 << 23;
const RTM: u32 = 1 << 11;
const RTM_ALWAYS_ABORT: u32 = 1 << 11;
const APX_F: u32 = 1 << 21;
const AESKLE: u32 = 1 << 0;
const WIDE_KL: u32 = 1 << 2;

const HWCAP2_FSGSBASE: u64 = 2;
const XCR0_SSE: u32 = 1 << 1;
const XCR0_AVX: u32 = 1 << 2;
const XCR0_AVX512: u32 = (1 << 5) | (1 << 6) | (1 << 7);
const XCR0_AMX: u32 = (1 << 17) | (1 << 18);
const XCR0_APX: u32 = 1 << 19;
const AT_HWCAP2: u64 = 26;

fn cpuid(leaf: u32, sub: u32) -> [u32; 4] {
    let (a, b, c, d): (u32, u32, u32, u32);
    // SAFETY: CPUID exists on every x86-64 processor. rbx is reserved by LLVM, so it is saved by hand.
    unsafe {
        asm!("mov {tmp:r}, rbx", "cpuid", "xchg {tmp:r}, rbx", tmp = out(reg) b, inout("eax") leaf => a, inout("ecx") sub => c, out("edx") d, options(nostack, preserves_flags));
    }
    [a, b, c, d]
}

fn xgetbv0() -> u32 {
    let lo: u32;
    // SAFETY: only called when CPUID said OSXSAVE is set.
    unsafe {
        asm!("xgetbv", in("ecx") 0u32, out("eax") lo, out("edx") _, options(nostack, preserves_flags, nomem));
    }
    lo
}

/// Add the bits of `m` the CPU reports to the active masks.
fn add(active: &mut Masks, m: &Masks, t: &[CpuidFeature; LEAVES]) {
    for i in 0..LEAVES {
        for r in 0..4 {
            active[i][r] |= t[i].cpuid_array[r] & m[i][r];
        }
    }
}

fn compute() -> [CpuidFeature; LEAVES] {
    let mut t = [ZERO; LEAVES];
    let max_basic = cpuid(0, 0)[0];
    let max_ext = cpuid(0x8000_0000, 0)[0];
    // (leaf, subleaf, needs the basic maximum >= leaf (else the extended one))
    const SPEC: [(u32, u32); LEAVES] = [(1, 0), (7, 0), (0x8000_0001, 0), (0xd, 1), (0x8000_0007, 0), (0x8000_0008, 0), (7, 1), (0x19, 0), (0x14, 0), (0x24, 0)];
    for (i, &(leaf, sub)) in SPEC.iter().enumerate() {
        let ok = if leaf & 0x8000_0000 != 0 { max_ext >= leaf } else { max_basic >= leaf };
        if ok {
            t[i].cpuid_array = cpuid(leaf, sub);
        }
    }
    let mut active: Masks = [[0u32; 4]; LEAVES];
    add(&mut active, &ALWAYS, &t);
    // RTM is usable unless the CPU says transactions always abort
    if t[1].cpuid_array[3] & RTM_ALWAYS_ABORT == 0 {
        active[1][1] |= t[1].cpuid_array[1] & RTM;
    }
    let osxsave = t[0].cpuid_array[2] & (1 << 27) != 0;
    if osxsave {
        let xcr0 = xgetbv0();
        let avx = xcr0 & (XCR0_SSE | XCR0_AVX) == (XCR0_SSE | XCR0_AVX);
        if avx {
            add(&mut active, &AVX_STATE, &t);
            if xcr0 & XCR0_AVX512 == XCR0_AVX512 && t[1].cpuid_array[1] & (1 << 16) != 0 {
                add(&mut active, &AVX512_STATE, &t);
                active[1][1] |= t[1].cpuid_array[1] & (1 << 16); // AVX512F itself
            }
        }
        if xcr0 & XCR0_AMX == XCR0_AMX {
            add(&mut active, &AMX_STATE, &t);
        }
        if xcr0 & XCR0_APX != 0 {
            active[6][3] |= t[6].cpuid_array[3] & APX_F;
        }
        add(&mut active, &XSAVE_STATE, &t);
    }
    // protection keys: usable when the OS enabled them (OSPKE); key locker needs AESKLE
    if t[1].cpuid_array[2] & OSPKE != 0 {
        active[1][2] |= t[1].cpuid_array[2] & PKU;
    }
    if t[7].cpuid_array[1] & AESKLE != 0 {
        active[7][1] |= AESKLE;
        active[1][2] |= t[1].cpuid_array[2] & KL;
        active[7][1] |= t[7].cpuid_array[1] & WIDE_KL;
    }
    // FSGSBASE only when the kernel enabled the instructions for user space
    if t[1].cpuid_array[1] & FSGSBASE != 0 && auxv::get(AT_HWCAP2).unwrap_or(0) & HWCAP2_FSGSBASE != 0 {
        active[1][1] |= FSGSBASE;
    }
    apply_tunables(&mut active, &t);
    for i in 0..LEAVES {
        t[i].active_array = active[i];
    }
    t
}

/// `GLIBC_TUNABLES=glibc.cpu.hwcaps=-AVX2,...` (glibc's `set_hwcaps`): a `-NAME` takes the feature out of the active set
/// (the names of sysdeps/x86/cpu-tunables.c), a plain `SHSTK` puts it back when the CPU has it. Read from the environment when
/// the table is first built (glibc: at start-up); the loader or the start-up code has already printed any complaint, and a
/// secure program or `glibc.rtld.enable_secure=1` gets no tunables. The preferred-feature names (`Prefer_ERMS`, ...) and the
/// state-size effect of `-XSAVEC` have nothing to act on here.
fn apply_tunables(active: &mut Masks, t: &[CpuidFeature; LEAVES]) {
    // SAFETY: getenv returns NULL or a NUL-terminated string of the environment.
    let p = unsafe { rusty_libc_core::env::getenv(b"GLIBC_TUNABLES") } as *const u8;
    if p.is_null() || auxv::get(auxv::AT_SECURE).unwrap_or(0) != 0 {
        return;
    }
    // SAFETY: as above (non-NULL here); the environment string stays valid while it is parsed. A byte loop like the old one
    // (not the dispatched strlen).
    let v = unsafe { rusty_libc_core::ffi::cstr_bytes_scalar(p) };
    let tun = tunables::parse(v, &mut |_| {});
    if tun.enable_secure {
        return;
    }
    if let Some(list) = tun.hwcaps {
        tunables::hwcaps_items(list, |name, disable| {
            if let Some((leaf, reg, bit, both)) = tunables::hwcap_feature(name) {
                let m = 1u32 << bit;
                if disable {
                    active[leaf][reg] &= !m;
                } else if both {
                    active[leaf][reg] |= t[leaf].cpuid_array[reg] & m;
                }
            }
        });
    }
}

static STATE: AtomicU8 = AtomicU8::new(0);
/// Rule: written once, by the thread that moved `STATE` from 0 to 1, before its Release store of 2; read only after an
/// Acquire load of `STATE` saw 2.
static TABLE: SyncCell<[CpuidFeature; LEAVES]> = SyncCell::new([ZERO; LEAVES]);

fn table() -> &'static [CpuidFeature; LEAVES] {
    loop {
        match STATE.load(Ordering::Acquire) {
            2 => break,
            0 => {
                if STATE.compare_exchange(0, 1, Ordering::Acquire, Ordering::Relaxed).is_ok() {
                    // SAFETY: only the thread that moved the state to 1 writes the table, before the release store.
                    unsafe { TABLE.write(compute()) };
                    STATE.store(2, Ordering::Release);
                    break;
                }
            }
            _ => core::hint::spin_loop(),
        }
    }
    // SAFETY: STATE is 2 (seen with Acquire, or stored by this thread), so the table is written and never changes again.
    unsafe { &*TABLE.as_ptr() }
}

/// `const struct cpuid_feature *__x86_get_cpuid_feature_leaf(unsigned int leaf)`: the table of leaf `leaf`
/// (CPUID_INDEX_1 ... CPUID_INDEX_24_ECX_0), or an all-zero one for a number out of range.
///
/// # Safety
/// Always safe to call; `unsafe` only because it is a C function.
#[cfg_attr(feature = "export", unsafe(no_mangle))]
pub unsafe extern "C" fn __x86_get_cpuid_feature_leaf(leaf: u32) -> *const CpuidFeature {
    if (leaf as usize) < LEAVES { &table()[leaf as usize] } else { &ZERO }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::undocumented_unsafe_blocks, clippy::multiple_unsafe_ops_per_block)]
    use super::*;

    #[test]
    fn leaves_match_the_processor() {
        let t = unsafe { &*__x86_get_cpuid_feature_leaf(0) };
        let c = cpuid(1, 0);
        // eax, ecx and edx are the same on every core; ebx holds the APIC id
        assert_eq!(t.cpuid_array[0], c[0]);
        assert_eq!(t.cpuid_array[2], c[2]);
        assert_eq!(t.cpuid_array[3], c[3]);
        // active is a subset of present, in every leaf
        for leaf in 0..LEAVES as u32 {
            let f = unsafe { &*__x86_get_cpuid_feature_leaf(leaf) };
            for r in 0..4 {
                assert_eq!(f.active_array[r] & !f.cpuid_array[r], 0, "leaf {leaf} reg {r}");
            }
        }
        // SSE2 is always there on x86-64
        assert_ne!(t.active_array[3] & (1 << 26), 0);
        let out = unsafe { &*__x86_get_cpuid_feature_leaf(10) };
        assert_eq!(out.cpuid_array, [0; 4]);
        assert_eq!(out.active_array, [0; 4]);
    }
}
