#!/usr/bin/env python3
"""Generates tab_yrows.rs: Taylor rows of the entire series E(u) of y0 and y1 on 0 <= x <= 1.25.

    python3 gen_yrows.py > tab_yrows.rs

y0(x) = (2/pi) j0(x) ln x + E0(u),  y1(x) = -2/(pi x) + (x/2) ((2/pi) ln x K(u) + E1(u)),  u = x^2/4,
with the coefficients E_k of `Y0_E` and `Y1_E` in tab_bessel.rs (read from that file: double-doubles,
exact rational arithmetic here). Same layout as tab_jrows.rs: row j holds the Taylor coefficients
g_0..g_6 at u = j/128 (g_0 and g_1 as double-doubles, the rest as doubles), |d| <= 1/256.
"""
import os
import re
from fractions import Fraction
from math import comb

ROWS = 51
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "tab_bessel.rs")).read()


def coeffs(name):
    m = re.search(r"pub\(super\) static " + name + r": \[\[f64; 2\]; \d+\] = \[(.*?)\n\];", src, re.S)
    pairs = re.findall(r"\[([^\],]+), ([^\]]+)\]", m.group(1))
    return [Fraction(float(h)) + Fraction(float(l)) for h, l in pairs]


def lit(v):
    return repr(float(v))


def row(a, j):
    c = Fraction(j, 128)
    g = [sum(comb(m, k) * a[m] * c ** (m - k) for m in range(k, len(a))) for k in range(7)]
    out = []
    for k in (0, 1):
        h = Fraction(float(g[k]))
        out += [lit(h), lit(g[k] - h)]
    out += [lit(g[k]) for k in range(2, 7)]
    return "[" + ", ".join(out) + "]"


print("// Generated by gen_yrows.py; do not edit.")
for name, tab in (("Y0E_ROWS", "Y0_E"), ("Y1E_ROWS", "Y1_E")):
    print()
    print(f"/// E(u) Taylor rows of {tab} at u = j/128, j = 0..={ROWS - 1}: [g0 hi, g0 lo, g1 hi, g1 lo, g2, g3, g4, g5, g6].")
    print(f"pub const {name}: [[f64; 9]; {ROWS}] = [")
    a = coeffs(tab)
    for j in range(ROWS):
        print("    " + row(a, j) + ",")
    print("];")
