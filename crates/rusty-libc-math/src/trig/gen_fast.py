def tan_taylor(j, den):
    s, c = sincos_fp(j, den)
    g = [(s * ONE) // c if c else 0]
    g.append(ONE + mul(g[0], g[0]))
    for n in range(1, DEG):
        acc = 0
        for i in range(n + 1):
            acc += mul(g[i], g[n - i])
        g.append(acc // (n + 1))
    return g


