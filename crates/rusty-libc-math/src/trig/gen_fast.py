#!/usr/bin/env python3
from fractions import Fraction
import math

P = 400
ONE = 1 << P


def mul(a, b):
    return (a * b) >> P


def sincos_fp(num, den):
    x = (num * ONE) // den
    x2 = mul(x, x)
    s = 0
    c = 0
    t = x
    k = 1
    while t:
        s += t if (k // 2) % 2 == 0 else -t
        t = mul(t, x2) // ((k + 1) * (k + 2))
        k += 2
    t = ONE
    k = 0
    while t:
        c += t if (k // 2) % 2 == 0 else -t
        t = mul(t, x2) // ((k + 1) * (k + 2))
        k += 2
    return s, c


def atan_inv(n):
    x = ONE // n
    n2 = n * n
    s = x
    k = 1
    sign = -1
    while x:
        x //= n2
        k += 2
        s += sign * (x // k)
        sign = -sign
    return s


PI = 4 * (4 * atan_inv(5) - atan_inv(239))


def atan_fp(num, den):
    x = (num * ONE) // den
    h = 0
    for _ in range(6):
        s = math.isqrt(ONE * ONE + x * x)
        x = (x * ONE) // (ONE + s)
        h += 1
    x2 = mul(x, x)
    term = x
    s = x
    k = 1
    sign = -1
    while term:
        term = mul(term, x2)
        k += 2
        s += sign * (term // k)
        sign = -sign
    return s << h


def frac(v):
    return Fraction(v, ONE)


def dd(fr):
    hi = float(fr)
    lo = float(fr - Fraction(hi))
    return hi, lo


def lit(x):
    r = repr(x)
    if 'e' not in r and '.' not in r:
        r += '.0'
    return r


def out(s=""):
    print(s)


out("//! Constant tables for trig/fast.rs. GENERATED by gen_fast.py (same directory) from exact")
out("//! big-integer arithmetic; derived data, nothing copied from another library. Do not edit.")
out("#![allow(clippy::excessive_precision, clippy::unreadable_literal, clippy::approx_constant, dead_code)]")
out()
N = 64
K = 64
out("/// (sin, cos) of k/64 for k = 0..=63, each as (hi, lo, hi, lo): S_hi, S_lo, C_hi, C_lo.")
out("pub const SINCOS_TAB: [[f64; 4]; %d] = [" % K)
for k in range(K):
    s, c = sincos_fp(k, N)
    sh, sl = dd(frac(s))
    ch, cl = dd(frac(c))
    out("    [%s, %s, %s, %s]," % (lit(sh), lit(sl), lit(ch), lit(cl)))
out("];")


def top_bits(fr, nbits):
    e = 0
    while fr >= 2 ** (e + 1):
        e += 1
    while fr < Fraction(2) ** e:
        e -= 1
    q = Fraction(2) ** (e - nbits + 1)
    return Fraction(math.floor(fr / q)) * q


def sincos_angle(j):
    ang = (j * PI) // 128
    q, r = divmod(j % 256, 64)
    rr = (r * PI) // 128
    x = rr
    x2 = mul(x, x)
    s = 0
    t = x
    k = 1
    while t:
        s += t if (k // 2) % 2 == 0 else -t
        t = mul(t, x2) // ((k + 1) * (k + 2))
        k += 2
    c = 0
    t = ONE
    k = 0
    while t:
        c += t if (k // 2) % 2 == 0 else -t
        t = mul(t, x2) // ((k + 1) * (k + 2))
        k += 2
    for _ in range(q):
        s, c = c, -s
    if r == 0:
        s = [0, ONE, 0, -ONE][q]
        c = [ONE, 0, -ONE, 0][q]
    return s, c


out()
out("/// (sin, cos) of j*pi/128 for j = 0..=255 as [S_hi, S_lo, C_hi, C_lo] (exact zeros where exact).")
out("pub const SINCOS128: [[f64; 4]; 256] = [")
for j in range(256):
    s, c = sincos_angle(j)
    sh, sl = dd(frac(s))
    ch, cl = dd(frac(c))
    out("    [%s, %s, %s, %s]," % (lit(sh), lit(sl), lit(ch), lit(cl)))
out("];")
out()
