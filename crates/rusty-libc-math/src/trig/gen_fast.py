def bernoulli(nmax):
    B = [Fraction(0)] * (nmax + 1)
    B[0] = Fraction(1)
    for m in range(1, nmax + 1):
        B[m] = -sum(comb(m + 1, k) * B[k] for k in range(m)) / (m + 1)
    return B


BN = bernoulli(40)
tc = []
for n in range(1, 12):
    c = Fraction(2 ** (2 * n) * (2 ** (2 * n) - 1)) * BN[2 * n] / math.factorial(2 * n)
    tc.append(c)
