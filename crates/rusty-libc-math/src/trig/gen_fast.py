out("pub const LOG128: [[f64; 3]; 91] = [")
for j in range(-37, 54):
    cinv = (ONE << P) // (((128 + j) * ONE) // 128)
    ih = float(frac(cinv))
    fr = Fraction(ih)
    num, den = fr.denominator - fr.numerator, fr.denominator + fr.numerator
    if num == 0:
        lc = 0
    elif num > 0:
        lc = 2 * atanh_fp(num, den)
    else:
        lc = -2 * atanh_fp(-num, den)
    lh, ll = dd(frac(lc))
    out("    [%s, %s, %s]," % (lit(ih), lit(lh), lit(ll)))
out("];")


