a1 = top_bits(step, 27)
a2 = top_bits(step - a1, 27)
a3 = step - a1 - a2
out("/// pi/128 = PI128_1 + PI128_2 + PI128_3; the first two have 27 bits (m * PI128_i exact for m < 2^26).")
out("pub const PI128_1: f64 = %s;" % lit(float(a1)))
out("pub const PI128_2: f64 = %s;" % lit(float(a2)))
