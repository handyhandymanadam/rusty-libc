out("/// tan(e pi/128) for e = -32..31 (index e + 32) as [hi, lo]: the table of the tangent kernels.")
out("pub const TAN64: [[f64; 2]; 64] = [")
for e in range(-32, 32):
    sn, cs = sincos_angle(e % 256)
    t = frac(sn) / frac(cs)
    th, tl = dd(t)
    out("    [%s, %s]," % (lit(th), lit(tl)))
out("];")
out("/// 128/pi.")
out("pub const INV_PI128: f64 = %s;" % lit(float(128 / frac(PI))))
b1 = float(step)
b2 = float(step - Fraction(b1))
b3 = float(step - Fraction(b1) - Fraction(b2))
out("/// pi/128 = PI128_B1 + PI128_B2 + PI128_B3, three non-overlapping doubles (fused-multiply-add reduction).")
out("pub const PI128_B1: f64 = %s;" % lit(b1))
out("pub const PI128_B2: f64 = %s;" % lit(b2))
out("pub const PI128_B3: f64 = %s;" % lit(b3))


from math import comb

DEG = 8


def row_out(g):
    h0, l0 = dd(frac(g[0]))
    h1, l1 = dd(frac(g[1]))
    rest = [float(frac(v)) for v in g[2:DEG + 1]]
    return "[%s, %s, %s, %s, %s]" % (lit(h0), lit(l0), lit(h1), lit(l1), ", ".join(lit(v) for v in rest))


def taylor_from_series(coef_fp, c_fp, mmax):
    pw = [ONE]
    for _ in range(mmax):
        pw.append(mul(pw[-1], c_fp))
    g = []
    for k in range(DEG + 1):
        acc = 0
        for m in range(k, mmax + 1):
            acc += comb(m, k) * mul(coef_fp[m], pw[m - k])
        g.append(acc)
    return g


MM = 260
R_COEF = [(comb(2 * m, m) << P) // (4 ** m * (2 * m + 1)) for m in range(MM + 1)]
Q_COEF = [(comb(2 * m, m) << P) // (8 ** m * (2 * m + 1)) for m in range(MM + 1)]

out()
out("/// asin(x) = x * R(x^2) near u = j/128: rows for j = 0..=32 (u up to 0.25).")
out("pub const ASIN_ROWS: [[f64; 11]; 33] = [")
for j in range(33):
    out("    " + row_out(taylor_from_series(R_COEF, (j << P) // 128, MM)) + ",")
out("];")
out()
out("/// acos(1 - w) = sqrt(2 w) * Q(w) near w = j/128: rows for j = 0..=64 (w up to 0.5).")
out("pub const ACOSQ_ROWS: [[f64; 11]; 65] = [")
for j in range(65):
    out("    " + row_out(taylor_from_series(Q_COEF, (j << P) // 128, MM)) + ",")
out("];")


def atan_taylor(c_num, c_den):
    c = (c_num << P) // c_den
    q0 = ONE + mul(c, c)
    q1 = 2 * c
    G = [(ONE << P) // q0]
    G.append(-((q1 * G[0]) // q0))
    for n in range(2, DEG):
        G.append(-(((q1 * G[n - 1]) >> P) + G[n - 2]) * ONE // q0)
    base = atan_fp(c_num, c_den) if c_num else 0
    g = [base] + [G[n] // (n + 1) for n in range(DEG)]
    return g


out()
out("/// atan(c + d) near c = j/128: rows for j = 0..=128.")
out("pub const ATAN_ROWS: [[f64; 11]; 129] = [")
for j in range(129):
    out("    " + row_out(atan_taylor(j, 128)) + ",")
out("];")



def ln2_fixed():
    s = 0
    t = ONE
    k = 1
    while t:
        t >>= 1
        s += t // k
        k += 1
    return s


LN2F = ln2_fixed()


def exp_fp(x):
    s = ONE
    t = ONE
    n = 1
    while t:
        t = mul(t, x) // n
        s += t
        n += 1
    return s


out()
out("/// [2^(j/128) hi, lo, 2^(-j/128) hi, lo] for j = 0..=127.")
out("pub const EXP128: [[f64; 4]; 128] = [")
for j in range(128):
    x = mul(LN2F, (j << P) // 128)
    e = exp_fp(x)
    ei = (ONE << P) // e
    th, tl = dd(frac(e))
    ih, il = dd(frac(ei))
    out("    [%s, %s, %s, %s]," % (lit(th), lit(tl), lit(ih), lit(il)))
out("];")
