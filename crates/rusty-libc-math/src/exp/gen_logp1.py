#!/usr/bin/env python3
"""Generates logp1_tab.rs: the table of the log2p1 / log10p1 kernel (dlog.rs, `logp1_tab`).
Usage: python3 gen_logp1.py > logp1_tab.rs

For each of the 256 cells j of z in [1 + j/256, 1 + (j+1)/256) the entry is [invc, lhi, llo]:
* invc: 1/(cell centre) rounded to 10 significant bits, so that invc * 2^-k - 1 is exact for k up to 43;
* lhi + llo = -ln(invc) = ln(1/invc), lhi the value rounded to a multiple of 2^-40 (so that k*LN2HI + lhi is exact for
  |k| < 64, LN2HI being ln 2 rounded to a multiple of 2^-40) and llo the rest, rounded to double (error about 2^-94).
Everything is computed here with Decimal (80 digits); nothing is copied from another library."""
from decimal import Decimal, getcontext
from fractions import Fraction
import struct

getcontext().prec = 80


def bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def lit(x):
    return "f64::from_bits(0x%016x)" % bits(x)


def to_double(d):
    return float(d)  # correctly rounded


GRID = 2 ** 40


def round_grid(d):
    return Decimal(int((d * GRID).to_integral_value())) / GRID


LN2 = Decimal(2).ln()
LN2HI = round_grid(LN2)
LN2LO = to_double(LN2 - LN2HI)

print("// GENERATED by gen_logp1.py (python3 gen_logp1.py > logp1_tab.rs). Do not edit.")
print("#![allow(clippy::unreadable_literal)]")
print()
print("/// ln 2 rounded to a multiple of 2^-40 (k * LN2HI is exact for |k| < 64) and the rest.")
print("pub(super) const LP1_LN2HI: f64 = %s; // %s" % (lit(to_double(LN2HI)), LN2HI))
print("pub(super) const LP1_LN2LO: f64 = %s; // %r" % (lit(LN2LO), LN2LO))
print()
print("/// Per cell of z = 1.xxxxxxxx (the top 8 mantissa bits) the bit patterns of [invc + 1023 in the exponent field, lhi, llo]: the first")
print("/// minus the exponent field of u (k + 1023, in place) is the pattern of invc 2^-k.")
print("pub(super) static LP1_TAB: [[u64; 3]; 256] = [")
for j in range(256):
    centre = Fraction(2 * j + 1, 512) + 1
    inv = Fraction(1) / centre
    n = round(inv * 1024)  # invc = n / 1024 with n in [512, 1024]: 10 significant bits
    invc = Fraction(n, 1024)
    lg = -(Decimal(invc.numerator) / Decimal(invc.denominator)).ln()
    lhi = round_grid(lg)
    llo = to_double(lg - lhi)
    print("    [0x%016x, 0x%016x, 0x%016x], // j=%d invc=%s" % (bits(float(invc)) + (1023 << 52), bits(to_double(lhi)), bits(llo), j, float(invc)))
print("];")
