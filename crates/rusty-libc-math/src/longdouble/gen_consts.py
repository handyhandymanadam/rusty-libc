from fractions import Fraction


def bernoulli(n):
    B = [Fraction(0)] * (n + 1)
    B[0] = Fraction(1)
    for m in range(1, n + 1):
        B[m] = -sum(math.comb(m + 1, k) * B[k] for k in range(m)) / (m + 1)
    return B


BERN = bernoulli(80)


def fp_frac(fr):
    return (fr.numerator * ONE) // fr.denominator


def ln_real(v):
    k = 0
    while v >= (3 * ONE) // 2:
        v >>= 1
        k += 1
    while v < (3 * ONE) // 4:
        v <<= 1
        k -= 1
    neg = v < ONE
    z = (abs(v - ONE) * ONE) // (v + ONE)
    z2 = (z * z) >> P
    t = z
    r = 0
    n = 1
    while t:
        r += t // n
        t = (t * z2) >> P
        n += 2
    return (-2 * r if neg else 2 * r) + k * LN2


BERN_FP = [fp_frac(b) for b in BERN]


def zeta_fp(k, N=60):
    s = sum(ONE // (n ** k) for n in range(1, N))
    s += ONE // ((k - 1) * N ** (k - 1)) + ONE // (2 * N ** k)
    for j in range(1, 40):
        rf = 1
        for i in range(2 * j - 1):
            rf *= (k + i)
        s += (BERN_FP[2 * j] * rf) // (math.factorial(2 * j) * N ** (k + 2 * j - 1))
    return s


def gamma_euler_fp(N=100):
    h = sum(ONE // n for n in range(1, N + 1))
    s = h - ONE // (2 * N)
    for k in range(1, 40):
        s += BERN_FP[2 * k] // (2 * k * N ** (2 * k))
    return s - ln_real(N * ONE)


