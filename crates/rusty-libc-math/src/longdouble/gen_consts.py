import math

P = 700
ONE = 1 << P


def atanh_inv(n, prec=P):
    one = 1 << prec
    x = one // n
    n2 = n * n
    s = 0
    k = 1
    while x:
        s += x // k
        x //= n2
        k += 2
    return s


def ln_ratio(num, den):
    a, b = num - den, num + den
    sign = 1
    if a < 0:
        a, sign = -a, -1
    x = (a * ONE) // b
    x2 = (x * x) >> P
    s = 0
    k = 1
    t = x
    while t:
        s += t // k
        t = (t * x2) >> P
        k += 2
    return sign * 2 * s


LN2 = 2 * atanh_inv(3)
LN10 = 3 * LN2 + ln_ratio(5, 4)


def atan_inv(n, prec):
    one = 1 << prec
    x = one // n
    n2 = n * n
    s = x
    k = 1
    sign = -1
    while x:
        x //= n2
        k += 2
        s += sign * (x // k)
        sign = -sign
    return s


def pi_fp(prec):
    return 4 * (4 * atan_inv(5, prec + 16) - atan_inv(239, prec + 16)) >> 16


PI = pi_fp(P)


def atan_fp(num, den):
    x = (num * ONE) // den
    for _ in range(5):
        s = math.isqrt(ONE * ONE + x * x)
        x = (x * ONE) // (ONE + s)
    x2 = (x * x) >> P
    t = x
    s = 0
    k = 1
    sign = 1
    while t:
        s += sign * (t // k)
        t = (t * x2) >> P
        k += 2
        sign = -sign
    return s << 5


def ext(f):
    assert f > 0
    L = f.bit_length()
    sh = L - 128
    m = (f + (1 << (sh - 1))) >> sh
    e = L - 1 - P
    if m >> 128:
        m >>= 1
        e += 1
    return e, m


def fmt(f):
    e, m = ext(f)
    return "Ext::c(false, %d, 0x%032x)" % (e, m)


def recip(f):
    return (ONE * ONE) // f


