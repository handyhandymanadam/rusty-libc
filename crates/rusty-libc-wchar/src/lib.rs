//! wchar.h, wctype.h and the wide-string half of stdlib.h: wide string and memory functions,
//! multibyte conversion (C locale and UTF-8), wide character classification.
//!
//! Unsafe areas (what stays unsafe, and where): the C boundary of the exported functions, which turns pointers into
//! slices, [`wcstr::WStr`] views, `&mut mbstate_t` and out-parameters once (core's `ffi`); the length scans of `wstring`
//! (SSE2) and the AVX2 kernels of `wvec`, which read whole aligned vectors past a string's end but never past its page
//! (each load or store one audited block; the value intrinsics are safe calls inside `target_feature` functions);
//! `WStr`'s lazy reads, which never go past the 0; the hidden conversion states of `mbyte` (`SyncCell`s: C11 lets calls
//! with a null state race); the calls through the charset hooks of rusty-libc-locale and the collation hooks of core
//! (raw-pointer signatures); published locale data (the thread's LC_CTYPE flags, the codeset name, the wide tables);
//! the naked `wcstold`/`wcstof128` entry points (x87 and xmm0 returns); the digit-grouping rewrite of rusty-libc-stdlib.
//! Everything else (UTF-8 and ASCII decoding and encoding, the string converters, the wcsto* parsers, classification and
//! case mapping, the Two-Way search, the Rust API) is safe code.
// `#[rustc_align(64)]` on the naked wmemcpy/wmemmove/wmempcpy (a naked function is otherwise placed at 4-byte alignment).
#![feature(fn_align)]
#![cfg_attr(not(test), no_std)]
// Without this LLVM turns the hand-written wcslen loop back into a call to wcslen, which a Rust
// program linking this crate without the `export` feature does not have (checked: link error).
#![no_builtins]
#![allow(clippy::missing_safety_doc)]
// Thin unsafe shell, safe core (BRIEF-UNSAFE.md U2): every unsafe block holds one unsafe operation and says why it is sound.
#![deny(clippy::undocumented_unsafe_blocks, clippy::multiple_unsafe_ops_per_block, unsafe_op_in_unsafe_fn)]

mod tables; // generated by tools/gen_tables.py: UTF-8 locale classification, case and width data
mod wvec; // AVX2 kernels of the wide-string functions
pub mod wcstr; // WStr: a C wide string seen from safe code (measured, or read lazily up to its 0)
pub mod wstring; // wcslen, wcscpy, wmemcpy ... (the wide twins of string.h)
pub mod mbyte; // mbrtowc, wcrtomb, mbsrtowcs, wcsrtombs, mblen, mbtowc, wctomb, mbstowcs, wcstombs, btowc, wctob, mbsinit
pub mod wctype; // iswalpha ..., towlower, towupper, wctype, iswctype, wctrans, towctrans, wcwidth, wcswidth
pub mod wtime; // wcsftime, wcsftime_l (the strftime engine of rusty-libc-time over wide characters)
pub mod wconv; // wcstol family, wcstod family, wcscoll, wcsxfrm

use core::sync::atomic::{AtomicU8, Ordering};

/// C `wchar_t` on Linux: a signed 32-bit integer.
#[allow(non_camel_case_types)]
pub type wchar_t = i32;
/// C `wint_t`: an unsigned 32-bit integer.
#[allow(non_camel_case_types)]
pub type wint_t = u32;
/// End of file marker of the wide functions.
pub const WEOF: wint_t = 0xffff_ffff;

/// The conversion state of the restartable multibyte functions: glibc's layout
/// `{ int __count; union { wint_t __wch; char __wchb[4]; } __value; }` (8 bytes). The UTF-8
/// decoder keeps the number of bytes seen so far in the low byte of `count`, the number the whole
/// sequence needs in bits 8.., and the bits read so far in `value`, exactly as glibc does.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[allow(non_camel_case_types)]
pub struct mbstate_t {
    pub count: i32,
    pub value: u32,
}

/// The character set the multibyte and wide character functions use, kept in sync with LC_CTYPE by
/// rusty-libc-locale's `setlocale` (the process-wide one) and `uselocale` (per thread): `C` is the plain
/// "C"/"POSIX" locale (ASCII only), `Utf8` is what "C.UTF-8" and "en_US.UTF-8" do.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Charset {
    C,
    Utf8,
    /// Any other charset the locale names (ISO-8859-x, KOI8-R, EUC-JP, ...): converted with
    /// rusty-libc-iconv, one character at a time (see `mbyte`).
    Other,
}

static CHARSET: AtomicU8 = AtomicU8::new(0);

/// Select the character set (what `setlocale(LC_CTYPE, ...)` will do later).
pub fn set_charset(c: Charset) {
    CHARSET.store(c as u8, Ordering::Relaxed);
}

/// The current character set (`C` at startup): the calling thread's `uselocale` locale if it has
/// one (its LC_CTYPE data carries the charset code), else the process-wide one.
#[inline]
pub fn charset() -> Charset {
    let t = rusty_libc_core::locale::thread();
    if !t.is_null() {
        // SAFETY: a thread locale is an object starting with 13 category pointers; LC_CTYPE is the first.
        let d = unsafe { *t };
        if !d.is_null() {
            // SAFETY: published locale data lives forever.
            let code = unsafe { (*d).flags() } >> rusty_libc_core::locale::F_CHARSET_SHIFT & 0xff;
            return code_charset(code);
        }
    }
    code_charset(CHARSET.load(Ordering::Relaxed) as u32)
}

#[inline]
fn code_charset(code: u32) -> Charset {
    match code {
        0 => Charset::C,
        1 => Charset::Utf8,
        _ => Charset::Other,
    }
}

/// One lock for tests that touch global state (the charset, the host locale, the hidden states).
#[cfg(test)]
pub(crate) static LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());

/// Test helper: holds `LOCK`, selects a host locale and our charset together, and puts both back
/// to "C" when dropped.
#[cfg(test)]
pub(crate) struct Loc {
    _guard: std::sync::MutexGuard<'static, ()>,
}

#[cfg(test)]
#[allow(clippy::undocumented_unsafe_blocks)]
impl Loc {
    pub(crate) fn new(host_locale: &str, cs: Charset) -> Loc {
        let guard = LOCK.lock().unwrap_or_else(|e| e.into_inner());
        let name = std::ffi::CString::new(host_locale).unwrap();
        let r = unsafe { libc::setlocale(libc::LC_ALL, name.as_ptr()) };
        assert!(!r.is_null(), "host locale {host_locale} is missing");
        set_charset(cs);
        Loc { _guard: guard }
    }
    pub(crate) fn c() -> Loc {
        Loc::new("C", Charset::C)
    }
    pub(crate) fn utf8() -> Loc {
        Loc::new("C.UTF-8", Charset::Utf8)
    }
}

#[cfg(test)]
#[allow(clippy::undocumented_unsafe_blocks)]
impl Drop for Loc {
    fn drop(&mut self) {
        unsafe { libc::setlocale(libc::LC_ALL, c"C".as_ptr()) };
        set_charset(Charset::C);
    }
}
